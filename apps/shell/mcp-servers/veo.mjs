#!/usr/bin/env node
/**
 * Google Veo (video generation) as an MCP server over stdio. Same shape as
 * nano-banana.mjs: dependency-free, newline-delimited JSON-RPC, runs on the
 * app's own runtime or any Node.
 *
 * Veo renders for one to three minutes, longer than a tool call may take, so
 * the work is split: `generate_video` starts the job and returns at once,
 * `video_status` waits (up to a minute per call) and, when the clip is ready,
 * downloads it into the DuneOffice media store and returns the http URL the
 * Slides `insert_video` tool accepts.
 *
 * Environment:
 *   GEMINI_API_KEY             required (aistudio.google.com)
 *   VEO_MODEL                  default veo-3.1-fast-generate-preview;
 *                              veo-3.1-generate-preview for the higher-quality, pricier model
 *   GEMINI_API_BASE            default https://generativelanguage.googleapis.com
 *   DUNEOFFICE_IMAGE_DIR       where clips go (set by DuneOffice)
 *   DUNEOFFICE_IMAGE_URL_BASE  http origin+prefix DuneOffice serves that dir from
 *   VEO_OUTPUT_DIR             fallback dir outside DuneOffice
 */
import { createInterface } from 'node:readline'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { extname, join } from 'node:path'
import { randomUUID } from 'node:crypto'

const SERVER = { name: 'veo', version: '1.0.0' }
const MODEL = process.env.VEO_MODEL || 'veo-3.1-fast-generate-preview'
const API_BASE = (
  process.env.GEMINI_API_BASE || 'https://generativelanguage.googleapis.com'
).replace(/\/+$/, '')
const OUT_DIR =
  process.env.DUNEOFFICE_IMAGE_DIR ||
  process.env.VEO_OUTPUT_DIR ||
  join(homedir(), '.genoffice', 'videos')
const URL_BASE = (process.env.DUNEOFFICE_IMAGE_URL_BASE || '').replace(/\/+$/, '')
const ASPECT_RATIOS = ['16:9', '9:16']
const DURATIONS = [4, 6, 8]
const RESOLUTIONS = ['720p', '1080p']
const MAX_WAIT_S = 60

/** job id → { operation, started, prompt, result? } */
const jobs = new Map()

const TOOLS = [
  {
    name: 'generate_video',
    description:
      'Start generating a short video clip (4, 6 or 8 seconds, with sound) with Google Veo from a text prompt, optionally animating a reference image as the first frame (an image made with nano-banana works well). Returns a job id immediately; rendering takes one to three minutes, so call video_status with the job id until it reports the clip. In slides the clip is inserted with insert_video using the URL video_status returns. Keep clips short and 720p unless the user asks for more: every second costs money and file size (an 8 s 720p clip is roughly 5–15 MB inside the .pptx). Describe motion, camera and mood in the prompt.',
    inputSchema: {
      type: 'object',
      properties: {
        prompt: {
          type: 'string',
          description:
            'What happens in the clip: subject, motion, camera movement, mood (English works best)',
        },
        aspect_ratio: { type: 'string', enum: ASPECT_RATIOS, description: 'default 16:9' },
        duration_seconds: { type: 'integer', enum: DURATIONS, description: 'default 8' },
        resolution: { type: 'string', enum: RESOLUTIONS, description: 'default 720p' },
        negative_prompt: { type: 'string', description: 'What to avoid in the clip' },
        reference_image_url: {
          type: 'string',
          description:
            'Optional first frame to animate: an http(s) URL, or the URL of an image generated by nano-banana',
        },
      },
      required: ['prompt'],
    },
  },
  {
    name: 'video_status',
    description:
      'Check a generate_video job. Waits up to wait_seconds (default 45) for the clip before answering, so call it repeatedly until it returns the finished clip URL or an error.',
    inputSchema: {
      type: 'object',
      properties: {
        job_id: { type: 'string' },
        wait_seconds: { type: 'integer', description: `0–${MAX_WAIT_S}, default 45` },
      },
      required: ['job_id'],
    },
  },
]

// ── JSON-RPC over stdio ───────────────────────────────────

function send(message) {
  process.stdout.write(JSON.stringify(message) + '\n')
}
function reply(id, result) {
  send({ jsonrpc: '2.0', id, result })
}
function replyError(id, code, message) {
  send({ jsonrpc: '2.0', id, error: { code, message } })
}

async function handle(msg) {
  const { id, method, params } = msg
  if (method === 'notifications/initialized' || method === 'notifications/cancelled') return
  if (id === undefined) return
  switch (method) {
    case 'initialize':
      reply(id, {
        protocolVersion: params?.protocolVersion || '2025-06-18',
        capabilities: { tools: {} },
        serverInfo: SERVER,
      })
      return
    case 'ping':
      reply(id, {})
      return
    case 'tools/list':
      reply(id, { tools: TOOLS })
      return
    case 'tools/call':
      try {
        reply(id, await callTool(params?.name, params?.arguments ?? {}))
      } catch (err) {
        reply(id, { content: [{ type: 'text', text: String(err?.message ?? err) }], isError: true })
      }
      return
    default:
      replyError(id, -32601, `Method not found: ${method}`)
  }
}

// ── Tools ─────────────────────────────────────────────────

function textResult(text, isError = false) {
  return { content: [{ type: 'text', text }], isError }
}

function apiHeaders(key) {
  return { 'content-type': 'application/json', 'x-goog-api-key': key }
}

async function loadReference(ref) {
  if (URL_BASE && ref.startsWith(URL_BASE + '/')) {
    const name = decodeURIComponent(ref.slice(URL_BASE.length + 1)).replace(/[\\/]/g, '')
    const data = readFileSync(join(OUT_DIR, name))
    const ext = extname(name).toLowerCase()
    return {
      mimeType:
        ext === '.jpg' || ext === '.jpeg'
          ? 'image/jpeg'
          : ext === '.webp'
            ? 'image/webp'
            : 'image/png',
      data: data.toString('base64'),
    }
  }
  if (!/^https?:\/\//.test(ref)) throw new Error('reference_image_url must be an http(s) URL')
  const res = await fetch(ref)
  if (!res.ok) throw new Error(`Could not fetch the reference image (HTTP ${res.status})`)
  const mimeType = (res.headers.get('content-type') || 'image/png').split(';')[0]
  return { mimeType, data: Buffer.from(await res.arrayBuffer()).toString('base64') }
}

async function startJob(key, args) {
  const prompt = String(args.prompt ?? '').trim()
  if (!prompt) return textResult('prompt must not be empty', true)
  const instance = { prompt }
  if (typeof args.reference_image_url === 'string' && args.reference_image_url.trim()) {
    const ref = await loadReference(args.reference_image_url.trim())
    instance.image = { bytesBase64Encoded: ref.data, mimeType: ref.mimeType }
  }
  const parameters = {
    aspectRatio: ASPECT_RATIOS.includes(args.aspect_ratio) ? args.aspect_ratio : '16:9',
    durationSeconds: DURATIONS.includes(Number(args.duration_seconds))
      ? Number(args.duration_seconds)
      : 8,
    resolution: RESOLUTIONS.includes(args.resolution) ? args.resolution : '720p',
    ...(typeof args.negative_prompt === 'string' && args.negative_prompt.trim()
      ? { negativePrompt: args.negative_prompt.trim() }
      : {}),
  }
  const res = await fetch(
    `${API_BASE}/v1beta/models/${encodeURIComponent(MODEL)}:predictLongRunning`,
    {
      method: 'POST',
      headers: apiHeaders(key),
      body: JSON.stringify({ instances: [instance], parameters }),
    },
  )
  const json = await res.json().catch(() => ({}))
  if (!res.ok || !json.name) {
    const detail = json?.error?.message || res.statusText || `HTTP ${res.status}`
    return textResult(`Veo request failed: ${detail}`, true)
  }
  const jobId = randomUUID().slice(0, 8)
  jobs.set(jobId, { operation: json.name, started: Date.now(), prompt, parameters })
  return textResult(
    `Video job ${jobId} started (${parameters.durationSeconds} s, ${parameters.resolution}, ${parameters.aspectRatio}). Rendering takes one to three minutes: call video_status with job_id "${jobId}" until it returns the clip.`,
  )
}

async function pollOnce(key, job) {
  const res = await fetch(`${API_BASE}/v1beta/${job.operation}`, { headers: apiHeaders(key) })
  const json = await res.json().catch(() => ({}))
  if (!res.ok) {
    throw new Error(json?.error?.message || res.statusText || `HTTP ${res.status}`)
  }
  return json
}

function videoUriOf(operation) {
  const r = operation.response ?? {}
  const samples = r.generateVideoResponse?.generatedSamples ?? r.generatedSamples ?? r.videos ?? []
  const first = samples[0]
  return first?.video?.uri ?? first?.uri ?? first?.videoUri ?? null
}

async function finishJob(key, jobId, job, operation) {
  if (operation.error) {
    jobs.delete(jobId)
    return textResult(
      `Veo failed: ${operation.error.message ?? JSON.stringify(operation.error)}`,
      true,
    )
  }
  const uri = videoUriOf(operation)
  if (!uri) {
    jobs.delete(jobId)
    const filtered = operation.response?.generateVideoResponse?.raiMediaFilteredReasons
    return textResult(
      `Veo finished without a video${filtered ? ` (${filtered.join('; ')})` : ''}.`,
      true,
    )
  }
  const res = await fetch(uri, { headers: { 'x-goog-api-key': key } })
  if (!res.ok) throw new Error(`Could not download the clip (HTTP ${res.status})`)
  const bytes = Buffer.from(await res.arrayBuffer())
  mkdirSync(OUT_DIR, { recursive: true })
  const fileName = `veo-${randomUUID()}.mp4`
  const filePath = join(OUT_DIR, fileName)
  writeFileSync(filePath, bytes)
  jobs.delete(jobId)
  const mb = (bytes.length / 1048576).toFixed(1)
  if (URL_BASE) {
    return textResult(
      `Clip ready (${job.parameters.durationSeconds} s, ${job.parameters.resolution}, ${mb} MB). Insert it with insert_video using this url: ${URL_BASE}/${fileName}`,
    )
  }
  return textResult(`Clip ready (${mb} MB): ${filePath}`)
}

async function status(key, args) {
  const jobId = String(args.job_id ?? '').trim()
  const job = jobs.get(jobId)
  if (!job)
    return textResult(`Unknown job id "${jobId}" (jobs live only while this server runs).`, true)
  const waitS = Math.max(0, Math.min(MAX_WAIT_S, Number(args.wait_seconds ?? 45) || 0))
  const deadline = Date.now() + waitS * 1000
  for (;;) {
    const operation = await pollOnce(key, job)
    if (operation.done) return finishJob(key, jobId, job, operation)
    if (Date.now() >= deadline) {
      const elapsed = Math.round((Date.now() - job.started) / 1000)
      return textResult(
        `Job ${jobId} is still rendering (${elapsed} s so far). Call video_status again.`,
      )
    }
    await new Promise((r) => setTimeout(r, Math.min(10_000, Math.max(1000, deadline - Date.now()))))
  }
}

async function callTool(name, args) {
  const key = process.env.GEMINI_API_KEY
  if (!key) {
    return textResult(
      'GEMINI_API_KEY is not set. Add it to this server\'s "env" in mcp.json (get a key at aistudio.google.com).',
      true,
    )
  }
  if (name === 'generate_video') return startJob(key, args)
  if (name === 'video_status') return status(key, args)
  return textResult(`Unknown tool: ${name}`, true)
}

// ── main ──────────────────────────────────────────────────

const rl = createInterface({ input: process.stdin, crlfDelay: Infinity })
rl.on('line', (line) => {
  const trimmed = line.trim()
  if (!trimmed) return
  let msg
  try {
    msg = JSON.parse(trimmed)
  } catch {
    replyError(null, -32700, 'Parse error')
    return
  }
  void handle(msg).catch((err) => {
    if (msg?.id !== undefined) replyError(msg.id, -32603, String(err?.message ?? err))
  })
})
rl.on('close', () => process.exit(0))
